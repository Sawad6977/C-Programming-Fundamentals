#include<stdio.h>
//Relational operators
int main()
{
    int x,n;
    printf("enter a number of x: ");
    scanf("%d",&x);
    printf("enter a number of n: ");
    scanf("%d",&n);
    printf("The number is: %d \n", x+n);
    printf("The number is: %d \n", x-n);
    printf("The number is: %d \n", x*n);
    printf("The number is: %d \n", x/n);

    return 0;
}

